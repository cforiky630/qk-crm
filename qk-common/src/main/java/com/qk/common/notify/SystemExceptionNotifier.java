package com.qk.common.notify;

/**
 * 系统异常告警出口
 * <p>
 * 「业务异常」是预期内的失败，返回 code=0 + 提示就够了；「系统异常」是代码或依赖的缺陷，
 * 必须让运维知道，否则只有用户投诉才会发现。这个接口就是两者的分界点：
 * 应用侧只负责决定「什么时候告警、带上什么上下文」，怎么送出去由实现决定。
 * <p>
 * <b>实现约定：notify 不允许抛异常。</b>它一定是在「正在返回 500」的路径上被调用，
 * 告警再失败也不能把错误响应本身弄坏。（调用方另有一层 try/catch 兜底，这里是双保险。）
 */
public interface SystemExceptionNotifier {

    /**
     * 发送一条系统异常告警
     * <p>
     * 实现应该是非阻塞的：把告警交给异步通道后立刻返回，不要占用请求线程。
     *
     * @param alert 告警内容
     */
    void notify(SystemAlert alert);
}
